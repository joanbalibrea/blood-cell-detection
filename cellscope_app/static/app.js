"use strict";
const $ = id => document.getElementById(id);
let file = null, previewURL = null, report = null, busy = false, ready = false, classifierReady = false;
let sortKey = "number", sortDirection = 1, zoomBaseWidth = 0;
const classStyle = {RBC: "rbc", WBC: "wbc", Platelets: "platelet"};
const subtypeLabels = {basophil: "Basophils", eosinophil: "Eosinophils", immature_granulocytes: "Immature granulocytes", lymphocyte: "Lymphocytes", monocyte: "Monocytes", neutrophil: "Neutrophils", uncertain: "Uncertain", disagreement: "Model disagreement", failed: "Could not classify", not_run: "Not classified (detection only)"};
const statusLabels = {predicted: "Predicted · inspect crop", uncertain: "Uncertain · review", disagreement: "Model disagreement · review", failed: "Failed · review", not_run: "Not classified", not_applicable: "—"};
const percent = value => value == null ? "—" : value > .9999 && value < 1 ? ">99.99%" : value > 0 && value < .0001 ? "<0.01%" : (100 * value).toFixed(2) + "%";
const pretty = value => value ? value.replaceAll("_", " ").replace(/^./, c => c.toUpperCase()) : "—";

function message(text, kind = "") {
  $("message").textContent = text;
  $("message").className = "message " + kind;
}
function controls() {
  $("detect").disabled = !file || !ready || busy || ($("mode").value === "integrated" && !classifierReady);
  $("reset").disabled = !report || busy;
  $("remove").disabled = busy;
  $("confidence").disabled = busy;
  for (const id of ["mode", "subtype-confidence", "padding"]) $(id).disabled = busy;
  $("subtype-controls").hidden = $("mode").value === "detection";
  $("file-input").disabled = busy;
  $("dropzone").setAttribute("aria-disabled", String(busy));
  for (const type of ["png", "csv", "json"]) $("export-" + type).disabled = !report || busy;
  document.body.classList.toggle("loading", busy);
  $("detect-label").textContent = busy ? "Analyzing image…" : "Analyze Blood Smear";
}
function clearResults(announce = true) {
  report = null;
  for (const id of ["total", "rbc", "wbc", "platelets"]) $("count-" + id).textContent = "—";
  $("annotated").hidden = true;
  $("annotated").removeAttribute("src");
  $("annotated-empty").hidden = false;
  $("annotated-view").disabled = true;
  $("prediction-tag").textContent = "OUTPUT";
  $("table-count").textContent = "0";
  $("result-meta").textContent = "Results are generated by your local trained model.";
  const row = $("detections").insertRow();
  $("detections").replaceChildren(row);
  const cell = row.insertCell(); cell.colSpan = 7; cell.className = "table-empty";
  cell.textContent = "Upload a blood smear and select Analyze Blood Smear.";
  renderSubtypes();
  if (announce) message(file ? "Ready to analyze. Select Analyze Blood Smear." : "Choose an image to begin your analysis.");
  controls();
}
function removeImage() {
  if (busy) return;
  clearResults(false); file = null;
  if (previewURL) URL.revokeObjectURL(previewURL);
  previewURL = null;
  $("file-input").value = "";
  $("original").removeAttribute("src"); $("original").hidden = true;
  $("original-empty").hidden = false; $("original-view").disabled = true;
  $("file-info").hidden = true; $("image-meta").textContent = "AWAITING IMAGE";
  message("Choose an image to begin your analysis."); controls();
}
function selectFile(candidate) {
  if (busy || !candidate) return;
  if (!/\.(png|jpe?g)$/i.test(candidate.name)) return message("Choose a JPG, JPEG, or PNG image.", "error");
  if (candidate.size > 12 * 1024 * 1024) return message("Image too large. Maximum upload size is 12 MB.", "error");
  if (!candidate.size) return message("This file is empty. Choose a microscopy image.", "error");
  removeImage(); file = candidate; previewURL = URL.createObjectURL(file);
  $("filename").textContent = file.name;
  $("file-size").textContent = (file.size / 1024).toFixed(1) + " KB · local image";
  $("file-info").hidden = false;
  $("original").onload = () => {
    if ($("original").naturalWidth * $("original").naturalHeight > 16000000) {
      removeImage(); message("Image exceeds the 16 megapixel limit.", "error"); return;
    }
    $("original").hidden = false; $("original-empty").hidden = true; $("original-view").disabled = false;
    $("image-meta").textContent = `${$("original").naturalWidth} × ${$("original").naturalHeight} PX`;
  };
  $("original").onerror = () => { removeImage(); message("This file is not a readable image. Choose a valid JPEG or PNG.", "error"); };
  $("original").src = previewURL;
  message("Image ready. Select Analyze Blood Smear to run local inference."); controls();
}
async function analyze() {
  if (!file || busy || !ready) return;
  clearResults(false); busy = true; controls();
  message("Running trained models locally. Large images may take a moment.");
  const body = new FormData(); body.append("file", file);
  try {
    const query = new URLSearchParams({confidence: $("confidence").value, mode: $("mode").value, subtype_confidence: $("subtype-confidence").value, padding: $("padding").value});
    const response = await fetch("/api/analyze?" + query, {method: "POST", body});
    const data = await response.json();
    if (!response.ok) throw Error(typeof data.detail === "string" ? data.detail : "Invalid request. Check the image and confidence threshold.");
    report = data;
    $("annotated").src = data.annotated_image; $("annotated").hidden = false;
    $("annotated-empty").hidden = true; $("annotated-view").disabled = false;
    $("count-total").textContent = data.total_count;
    $("count-rbc").textContent = data.rbc_count; $("count-wbc").textContent = data.wbc_count;
    $("count-platelets").textContent = data.platelet_count;
    $("table-count").textContent = data.total_count;
    $("prediction-tag").textContent = "CONF ≥ " + data.confidence_threshold.toFixed(2);
    $("result-meta").textContent = `${data.total_count} objects · ${(data.elapsed_ms / 1000).toFixed(2)} s · CPU · confidence ≥ ${data.confidence_threshold.toFixed(2)}`;
    renderTable(); renderSubtypes();
    const flagged = data.detections.filter(d => d.classification.review_required).length;
    message(data.total_count ? `Analysis complete. ${data.total_count} objects detected. ${flagged} WBC results flagged for review.` : "Analysis complete. No cells detected at this threshold. Try lowering confidence.", "success");
  } catch (error) {
    message(error instanceof TypeError ? "Cannot reach the local server. Start CellScope and try again." : error.message, "error");
  } finally { busy = false; controls(); }
}
function renderTable() {
  const rows = [...report.detections].sort((a, b) => {
    const value = sortKey === "class_name" ? a.class_name.localeCompare(b.class_name) : a[sortKey] - b[sortKey];
    return sortDirection * value;
  });
  $("detections").replaceChildren();
  if (!rows.length) {
    const cell = $("detections").insertRow().insertCell(); cell.colSpan = 7; cell.className = "table-empty";
    cell.textContent = "No detections at this confidence threshold. Try a lower value and detect again.";
  }
  for (const detection of rows) {
    const row = $("detections").insertRow(); row.insertCell().textContent = String(detection.number).padStart(2, "0");
    const badge = document.createElement("span"); badge.className = "class-badge " + classStyle[detection.class_name];
    const dot = document.createElement("i"); dot.className = "dot"; badge.append(dot, detection.class_name);
    row.insertCell().append(badge);
    const cell = row.insertCell(); cell.className = "confidence-cell"; cell.textContent = (100 * detection.confidence).toFixed(1) + "%";
    const bar = document.createElement("span"); bar.className = "confidence-bar";
    const fill = document.createElement("i"); fill.style.width = (100 * detection.confidence) + "%"; bar.append(fill); cell.append(bar);
    const c = detection.classification;
    row.insertCell().textContent = pretty(c.predicted_class);
    row.insertCell().textContent = percent(c.confidence);
    const status = row.insertCell(); status.textContent = statusLabels[c.status];
    status.className = "review-status" + (c.review_required ? " flagged" : "");
    status.title = (c.warnings || []).join(" ");
    row.insertCell().textContent = Object.values(detection.bbox).map(n => n.toFixed(1)).join(", ");
  }
}
function renderSubtypes() {
  $("subtype-grid").replaceChildren(); $("wbc-gallery").replaceChildren();
  const counts = report?.wbc_breakdown.counts;
  for (const [key, label] of Object.entries(subtypeLabels)) {
    if (key === "not_run" && report?.mode !== "detection") continue;
    const card = document.createElement("div"); card.className = "subtype-card" + (["uncertain", "disagreement", "failed"].includes(key) ? " review" : "");
    const name = document.createElement("span"); name.textContent = label;
    const count = document.createElement("strong"); count.textContent = counts ? counts[key] : "—";
    card.append(name, count); $("subtype-grid").append(card);
    if (key === "disagreement" && report) {
      const other = report.wbc_breakdown.disagreement_predictions;
      card.title = `Erythroblast: ${other.erythroblast}; platelet: ${other.platelet}`;
      name.textContent = `${label} (erythroblast ${other.erythroblast} / platelet ${other.platelet})`;
    }
  }
  $("subtype-total").textContent = report ? `${report.wbc_breakdown.total} / ${report.wbc_count} YOLO WBCs accounted for` : "AWAITING ANALYSIS";
  if (report) $("domain-notice").textContent = report.domain_notice;
  const wbcs = report?.detections.filter(d => d.class_name === "WBC") || [];
  if (!wbcs.length || report?.mode === "detection") {
    const p = document.createElement("p"); p.className = "empty-gallery";
    p.textContent = !report ? "Analyze an image in integrated mode to inspect WBC crops." : report.mode === "detection" ? "Detection-only mode: WBC subtypes were not classified. Select integrated mode to inspect crops." : "No WBCs detected at this threshold.";
    $("wbc-gallery").append(p); return;
  }
  for (const detection of wbcs) {
    const c = detection.classification, card = document.createElement("article"); card.className = "wbc-card";
    if (detection.crop) {
      const button = document.createElement("button"); button.className = "crop-button";
      button.setAttribute("aria-label", `Enlarge WBC crop ${detection.number}`);
      const img = document.createElement("img"); img.src = detection.crop.image; img.alt = `WBC detection ${detection.number} crop`;
      img.id = `crop-${detection.number}`; button.append(img);
      button.onclick = () => enlarge(img.id, `WBC #${detection.number} · ${pretty(c.predicted_class)}`); card.append(button);
    } else {
      const missing = document.createElement("div"); missing.className = "crop-missing"; missing.textContent = "Crop unavailable"; card.append(missing);
    }
    const body = document.createElement("div"); body.className = "wbc-card-body";
    const number = document.createElement("span"); number.className = "small-label"; number.textContent = `YOLO WBC #${detection.number}`;
    const title = document.createElement("h3"); title.textContent = pretty(c.predicted_class);
    const scores = document.createElement("p"); scores.textContent = `C: ${percent(c.confidence)} · D: ${percent(detection.confidence)}`;
    const status = document.createElement("p"); status.className = "review-status" + (c.review_required ? " flagged" : ""); status.textContent = statusLabels[c.status];
    body.append(number, title, scores, status);
    for (const warning of c.warnings || []) { const p = document.createElement("p"); p.className = "review-warning"; p.textContent = warning; body.append(p); }
    if (c.top_predictions) { const p = document.createElement("p"); p.className = "alternatives"; p.textContent = "Top 3: " + c.top_predictions.map(v => `${pretty(v.class_name)} ${percent(v.confidence)}`).join(" · "); body.append(p); }
    if (detection.crop?.white_edge_padding) { const p = document.createElement("p"); p.textContent = "Image-edge context filled white."; body.append(p); }
    card.append(body); $("wbc-gallery").append(card);
  }
}
function save(blob, extension, filename = report.filename) {
  const url = URL.createObjectURL(blob), link = document.createElement("a");
  link.href = url; link.download = "cellscope-" + filename.replace(/\.[^.]+$/, "") + extension;
  document.body.append(link); link.click(); link.remove(); setTimeout(() => URL.revokeObjectURL(url), 1000);
}
$("export-png").onclick = async () => {
  const current = report;
  if (current) save(await (await fetch(current.annotated_image)).blob(), "-annotated.png", current.filename);
};
$("export-csv").onclick = () => {
  if (!report) return;
  save(new Blob([report.csv], {type: "text/csv;charset=utf-8"}), "-detections.csv");
};
$("export-json").onclick = () => {
  if (!report) return;
  save(new Blob([JSON.stringify(report, null, 2)], {type: "application/json"}), "-report.json");
};
for (const [id, key] of [["sort-class", "class_name"], ["sort-confidence", "confidence"]]) $(id).onclick = () => {
  sortDirection = sortKey === key ? -sortDirection : key === "confidence" ? -1 : 1; sortKey = key; if (report) renderTable();
};
function enlarge(id, title) {
  $("zoom-title").textContent = title; $("zoom-image").src = $(id).src;
  zoomBaseWidth = Math.min($(id).naturalWidth, window.innerWidth * .85);
  $("zoom").value = 100; $("zoom-value").textContent = "100%"; $("zoom-image").style.width = zoomBaseWidth + "px";
  $("zoom-dialog").showModal();
}
$("original-view").onclick = () => enlarge("original", "Original image");
$("annotated-view").onclick = () => enlarge("annotated", "Combined predictions · D = detector / C = classifier");
$("zoom").oninput = () => { $("zoom-value").textContent = $("zoom").value + "%"; $("zoom-image").style.width = zoomBaseWidth * $("zoom").value / 100 + "px"; };
$("close-zoom").onclick = () => $("zoom-dialog").close();
$("dropzone").onclick = () => { if (!busy) $("file-input").click(); };
$("dropzone").onkeydown = event => { if (event.key === "Enter" || event.key === " ") {event.preventDefault(); if (!busy) $("file-input").click();} };
$("file-input").onchange = event => selectFile(event.target.files[0]);
for (const event of ["dragenter", "dragover"]) $("dropzone").addEventListener(event, e => {e.preventDefault(); if (!busy) $("dropzone").classList.add("dragging");});
for (const event of ["dragleave", "drop"]) $("dropzone").addEventListener(event, e => {e.preventDefault(); $("dropzone").classList.remove("dragging");});
$("dropzone").addEventListener("drop", event => { if (event.dataTransfer.files.length > 1) message("Choose one image at a time.", "error"); else selectFile(event.dataTransfer.files[0]); });
$("remove").onclick = removeImage; $("reset").onclick = () => clearResults(); $("detect").onclick = analyze;
for (const id of ["confidence", "subtype-confidence", "padding", "mode"]) $(id).addEventListener(id === "mode" ? "change" : "input", () => {
  $("confidence-value").textContent = Number($("confidence").value).toFixed(2);
  $("subtype-confidence-value").textContent = Number($("subtype-confidence").value).toFixed(2);
  $("padding-value").textContent = Math.round(100 * $("padding").value) + "%";
  if (report) { clearResults(false); message("Settings changed. Analyze again to recalculate predictions."); }
  controls();
});
async function checkModel() {
  try {
    const response = await fetch("/api/health");
    if (!response.ok) throw Error("Server status unavailable.");
    const data = await response.json(); ready = data.ready; classifierReady = data.classifier?.ready === true;
    $("model-status").textContent = data.integrated_ready ? "Both models ready · CPU" : ready ? "Detector ready · CPU" : "Models unavailable";
    $("status-dot").classList.toggle("ready", ready);
    document.querySelector(".model-details>div>span").textContent = `CPU · ${data.imgsz} px`;
    const notices = [data.error, data.warning, data.classifier?.error].filter(Boolean);
    $("model-notice").textContent = notices.join(" "); $("model-notice").hidden = !notices.length;
    if (ready && !classifierReady) { $("mode").value = "detection"; message("Classifier unavailable. Detection-only mode is ready."); }
  } catch { $("model-status").textContent = "Server offline"; message("Cannot reach the local server. Start CellScope, then refresh this page.", "error"); }
  controls();
}
renderSubtypes(); checkModel();
